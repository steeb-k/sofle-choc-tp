#!/usr/bin/env python3
"""Render a word as a vertical bitmap for the left-half OLED and emit a C header.

The left OLED runs at OLED_ROTATION_270: a logical 32 px wide by 128 px tall
canvas, stored as 8-pixel vertical byte columns (index = x + (y / 8) * 32).
The word is drawn horizontally in a bold font, rotated so it reads from the
top of the screen downwards, and packed into that format for oled_write_raw_P.

Usage: make_oled_name.py [--text kznjk] [--lines 12] [--font path] [--size N]
Writes keymaps/sofle_choc_tp/oled_name.h and layout/oled_preview.png.
"""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
WIDTH = 32


def render(text: str, lines: int, font_path: str, size: int, rotate: int) -> Image.Image:
    height = lines * 8
    font = ImageFont.truetype(font_path, size)
    # Draw horizontally on a generous canvas, then crop to the ink.
    canvas = Image.new("1", (height * 2, WIDTH * 3), 0)
    draw = ImageDraw.Draw(canvas)
    draw.text((8, 8), text, font=font, fill=1)
    bbox = canvas.getbbox()
    if bbox is None:
        raise SystemExit("font rendered nothing")
    ink = canvas.crop(bbox)
    if ink.width > height or ink.height > WIDTH:
        raise SystemExit(f"'{text}' renders {ink.width}x{ink.height}, exceeds {height}x{WIDTH}; lower --size")
    # Center the word on a 128x32-style strip, then rotate it upright on the tall canvas.
    strip = Image.new("1", (height, WIDTH), 0)
    strip.paste(ink, ((height - ink.width) // 2, (WIDTH - ink.height) // 2))
    return strip.rotate(rotate, expand=True)  # -90: reads top to bottom, letter tops to the right


def pack(img: Image.Image) -> bytes:
    w, h = img.size
    assert w == WIDTH and h % 8 == 0
    px = img.load()
    out = bytearray()
    for page in range(h // 8):
        for x in range(w):
            b = 0
            for bit in range(8):
                if px[x, page * 8 + bit]:
                    b |= 1 << bit
            out.append(b)
    return bytes(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--text", default="kznjk")
    ap.add_argument("--lines", type=int, default=12, help="height in 8 px text lines")
    ap.add_argument("--font", default="/System/Library/Fonts/Supplemental/Arial Bold.ttf")
    ap.add_argument("--size", type=int, default=30)
    ap.add_argument("--rotate", type=int, default=-90, help="-90 reads downward with letter tops to the right; 90 the other way")
    ap.add_argument("--out", default=str(ROOT / "keymaps/sofle_choc_tp/oled_name.h"))
    ap.add_argument("--preview", default=str(ROOT / "layout/oled_preview.png"))
    args = ap.parse_args()

    img = render(args.text, args.lines, args.font, args.size, args.rotate)
    data = pack(img)

    body = []
    for page in range(args.lines):
        row = data[page * WIDTH:(page + 1) * WIDTH]
        body.append("    " + ", ".join(f"0x{b:02X}" for b in row) + ",")
    header = f"""// Generated by tools/make_oled_name.py -- do not edit by hand.
// '{args.text}' as a {WIDTH}x{args.lines * 8} bitmap for the OLED_ROTATION_270 left display,
// packed as vertical byte columns (oled_write_raw_P format, {args.lines} text lines tall).
#pragma once
#include <stdint.h>

#define OLED_NAME_LINES {args.lines}

static const char PROGMEM oled_name_bitmap[{WIDTH} * OLED_NAME_LINES] = {{
{chr(10).join(body)}
}};
"""
    Path(args.out).write_text(header)

    # Preview: the whole 32x128 screen scaled up, with the rule and text lines sketched in.
    screen = Image.new("1", (WIDTH, 128), 0)
    screen.paste(img, (0, 0))
    d = ImageDraw.Draw(screen)
    y = args.lines * 8 + 3
    d.line((0, y, WIDTH - 1, y), fill=1)
    d.line((0, y + 1, WIDTH - 1, y + 1), fill=1)
    small = ImageFont.load_default()
    d.text((0, (args.lines + 1) * 8 - 1), "Layer", font=small, fill=1)
    d.text((0, (args.lines + 2) * 8 - 1), "kbd", font=small, fill=1)
    screen.resize((WIDTH * 4, 128 * 4), Image.NEAREST).save(args.preview)
    print(f"wrote {args.out} ({len(data)} bytes) and {args.preview}")


if __name__ == "__main__":
    main()
